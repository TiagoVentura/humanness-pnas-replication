# ---- Config -----------------------------------------------------------------

MODEL            <- "gpt-5"
TEMPERATURE      <- 1
N_CALLS_PER_PAIR <- 3
PARALLEL_MAX     <- 8         # concurrent in-flight requests
REASONING_EFFORT <- "minimal"
SEED             <- 42


# ---- Packages ---------------------------------------------------------------

pacman::p_load(tidyverse, here, httr2, jsonlite, glue)

if (!exists("%||%", mode = "function")) {
  `%||%` <- function(x, y) if (is.null(x)) y else x
}

# ---- Paths ------------------------------------------------------------------

INPUT_PATH <- here("data", "all_pairs_wide_format.csv")
OUTPUT_PATH <- here(
  "data",
  paste0("gpt_detector_sample_", MODEL, "_all_posts_",
         format(Sys.time(), "%Y%m%d"), ".csv")
)

# ---- API key ----------------------------------------------------------------

api_key <- "ADD_YOUR_API_KEY"

# ---- Load + filter to mixed AI/Human pairs + stratified sample --------------
library(tidylog)

pairs_all <- read_csv(INPUT_PATH, show_col_types = FALSE)

mixed_pool <- pairs_all %>%
  filter(
    (source_left == "AI"    & source_right == "Human") |
    (source_left == "Human" & source_right == "AI")
  ) |>
  distinct(
    text_id_left, text_id_right, platform,
    post_left, post_right, source_left, source_right
  )

# Use ALL unique mixed pairs (no stratified subsample). SEED kept for the
# `runs` ordering below to make a partial-resume possible if needed.
sample_pairs <- mixed_pool

message(sprintf(
  "Running on FULL sample: %d unique mixed pairs x %d calls = %d total API calls.",
  nrow(sample_pairs), N_CALLS_PER_PAIR,
  nrow(sample_pairs) * N_CALLS_PER_PAIR
))
message(sprintf(
  "By platform: %s",
  paste(sprintf("%s=%d",
                names(table(sample_pairs$platform)),
                as.integer(table(sample_pairs$platform))),
        collapse = ", ")
))


# ---- Prompt -----------------------------------------------------------------

build_user_message <- function(post_left, post_right) {
  glue(
    "Please read carefully the two social media posts below.\n\n",
    "Post A: {post_left}\n\n",
    "Post B: {post_right}\n\n",
    "Which of the posts (Post A or Post B) is more likely to have been ",
    "generated by an AI chatbot?"
  )
}

response_schema <- list(
  type = "json_schema",
  json_schema = list(
    name   = "ai_detector_answer",
    strict = TRUE,
    schema = list(
      type                 = "object",
      additionalProperties = FALSE,
      required             = list("answer"),
      properties = list(
        answer = list(
          type = "string",
          enum = list("Post A", "Post B")
        )
      )
    )
  )
)

# ---- Build all requests up front -------------------------------------------

build_request <- function(user_msg) {
  body <- list(
    model            = MODEL,
    messages         = list(list(role = "user", content = user_msg)),
    temperature      = TEMPERATURE,
    response_format  = response_schema,
    reasoning_effort = REASONING_EFFORT
  )
  request("https://api.openai.com/v1/chat/completions") |>
    req_headers(
      Authorization  = paste("Bearer", api_key),
      `Content-Type` = "application/json"
    ) |>
    req_body_json(body, auto_unbox = TRUE) |>
    req_retry(max_tries = 5, backoff = ~ 2 ^ .x) |>
    req_timeout(180)
}

runs <- tidyr::crossing(
  sample_pairs |> mutate(.pair_idx = row_number()),
  call_number = seq_len(N_CALLS_PER_PAIR)
)

reqs <- lapply(seq_len(nrow(runs)), function(i) {
  build_request(build_user_message(runs$post_left[i], runs$post_right[i]))
})

# ---- Run in parallel --------------------------------------------------------

t_start <- Sys.time()
resps <- req_perform_parallel(
  reqs,
  max_active = PARALLEL_MAX,
  on_error   = "continue",
  progress   = TRUE
)
elapsed <- as.numeric(difftime(Sys.time(), t_start, units = "secs"))

# ---- Extract results --------------------------------------------------------

extract_result <- function(resp) {
  if (inherits(resp, "error")) {
    return(tibble(
      raw_response      = NA_character_,
      parsed_answer     = NA_character_,
      prompt_tokens     = NA_integer_,
      completion_tokens = NA_integer_,
      total_tokens      = NA_integer_,
      error             = conditionMessage(resp)
    ))
  }
  if (resp_status(resp) >= 400) {
    return(tibble(
      raw_response      = resp_body_string(resp),
      parsed_answer     = NA_character_,
      prompt_tokens     = NA_integer_,
      completion_tokens = NA_integer_,
      total_tokens      = NA_integer_,
      error             = paste("HTTP", resp_status(resp))
    ))
  }
  parsed <- resp_body_json(resp)
  raw    <- parsed$choices[[1]]$message$content
  answer <- tryCatch(fromJSON(raw)$answer, error = function(e) NA_character_)
  tibble(
    raw_response      = raw,
    parsed_answer     = answer,
    prompt_tokens     = parsed$usage$prompt_tokens     %||% NA_integer_,
    completion_tokens = parsed$usage$completion_tokens %||% NA_integer_,
    total_tokens      = parsed$usage$total_tokens      %||% NA_integer_,
    error             = NA_character_
  )
}

results_df <- map_dfr(resps, extract_result)
output <- bind_cols(runs, results_df) |>
  mutate(
    model            = MODEL,
    temperature      = TEMPERATURE,
    reasoning_effort = REASONING_EFFORT,
    timestamp        = format(Sys.time(), "%Y-%m-%dT%H:%M:%S%z")
  ) |>
  select(
    text_id_left, text_id_right, platform,
    source_left, source_right,
    post_left, post_right,
    call_number, model, temperature, reasoning_effort,
    raw_response, parsed_answer,
    prompt_tokens, completion_tokens, total_tokens,
    error, timestamp
  )

write_csv(output, OUTPUT_PATH)


